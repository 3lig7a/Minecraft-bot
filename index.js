const mineflayer = require('mineflayer');
const express = require('express');
const app = express();

// ?????? ?????? ???? ????? Replit ?? 3000 ????????
const PORT = process.env.PORT || 3000;

// ???? GET ????? ?????? ?? ?? ????? ??????? ??????
app.get('/', (req, res) => res.send('Bot is alive!'));

// ???? ???? ?????? ???????? ?????
app.get('/status', (req, res) => {
    res.json({
        status: 'running',
        username: bot?.username || 'bot not connected',
        connected: Boolean(bot?.entity),
        time: new Date().toISOString()
    });
});

// ????? ?????? ??? ?????? ??????
app.listen(PORT, () => {
    console.log('?? Express server running on port', PORT);
    console.log(`?? Public URL: running on port ${PORT}`);
});

// ????? ??? Mineflayer ???????? ????????
const bot = mineflayer.createBot({
    host: '_Survivors_.aternos.me',
    port: 45848,
    username: 'blackbot' + Math.floor(Math.random() * 1000),
    version: '1.21.6'
});

bot.on('spawn', () => {
    console.log('? Bot connected as', bot.username);
    setInterval(() => {
        bot.setControlState('jump', true);
        setTimeout(() => bot.setControlState('jump', false), 1000);
    }, 60000);
});

bot.on('end', () => {
    console.log('? Bot disconnected. Restarting...');
    setTimeout(() => process.exit(1), 1000);
});
